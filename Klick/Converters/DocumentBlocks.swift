import AppKit

/// A semantic view of attributed text (headings, paragraphs, lists, code, quotes, images) for the
/// writers AppKit doesn't have: Markdown, EPUB and clean HTML. Headings come from the paragraph's
/// `headerLevel` (HTML/Markdown imports) or, for DOCX/RTF, from bold text set larger than the body.
struct DocumentBlock {
    enum Kind: Equatable {
        case heading(Int)
        case paragraph
        case listItem(ordered: Bool, depth: Int)
        case code
        case quote
        /// `cells[row][column]`; the first row is the header.
        case table
    }

    struct Run {
        var text: String
        var bold = false
        var italic = false
        var code = false
        var strike = false
        var link: URL?
        /// Inline image (PNG/JPEG/GIF data) with its file extension.
        var image: (data: Data, ext: String)?

        func sameStyle(as other: Run) -> Bool {
            bold == other.bold && italic == other.italic && code == other.code && strike == other.strike && link == other.link
        }
    }

    var kind: Kind
    var runs: [Run]
    var cells: [[[Run]]] = []

    var plainText: String { runs.map(\.text).joined() }

    // MARK: - Parsing

    static func blocks(from text: NSAttributedString) -> [DocumentBlock] {
        let string = text.string as NSString
        let bodySize = dominantFontSize(of: text)
        var blocks: [DocumentBlock] = []
        var currentTable: NSTextTable?
        string.enumerateSubstrings(in: NSRange(location: 0, length: string.length), options: [.byParagraphs, .substringNotRequired]) { _, range, _, _ in
            // Table cells (one paragraph or more each) are collected into a single table block.
            let style = range.length > 0 ? text.attribute(.paragraphStyle, at: range.location, effectiveRange: nil) as? NSParagraphStyle : nil
            if let cell = style?.textBlocks.last as? NSTextTableBlock {
                if currentTable !== cell.table || blocks.last?.kind != .table {
                    blocks.append(DocumentBlock(kind: .table, runs: []))
                    currentTable = cell.table
                }
                let content = trimmed(runs(in: text, range: range))
                var table = blocks[blocks.count - 1].cells
                while table.count <= cell.startingRow { table.append([]) }
                while table[cell.startingRow].count <= cell.startingColumn { table[cell.startingRow].append([]) }
                if !table[cell.startingRow][cell.startingColumn].isEmpty && !content.isEmpty {
                    table[cell.startingRow][cell.startingColumn].append(Run(text: " "))
                }
                table[cell.startingRow][cell.startingColumn] += content
                blocks[blocks.count - 1].cells = table
                return
            }
            if range.length > 0 { currentTable = nil } // empty cells come through as empty paragraphs
            guard let block = block(in: text, range: range, bodySize: bodySize) else { return }
            // Consecutive monospaced paragraphs form one code block.
            if block.kind == .code, let last = blocks.last, last.kind == .code {
                blocks[blocks.count - 1].runs.append(Run(text: "\n" + block.plainText))
            } else {
                blocks.append(block)
            }
        }
        return blocks
    }

    private static func block(in text: NSAttributedString, range: NSRange, bodySize: CGFloat) -> DocumentBlock? {
        guard range.length > 0 else { return nil }
        let style = text.attribute(.paragraphStyle, at: range.location, effectiveRange: nil) as? NSParagraphStyle
        var runs = runs(in: text, range: range)

        // AppKit list items start with "\t<marker>\t"; the marker is generated by the writers.
        let lists = style?.textLists ?? []
        if !lists.isEmpty, let first = runs.first, let marker = first.text.range(of: #"^\t?[^\t]{0,12}\t"#, options: .regularExpression) {
            runs[0].text.removeSubrange(marker)
        }
        let visible = runs.contains { $0.image != nil || !$0.text.trimmingCharacters(in: .whitespaces).isEmpty }
        guard visible else { return nil }

        if let list = lists.last {
            return DocumentBlock(kind: .listItem(ordered: isOrdered(list), depth: lists.count), runs: trimmed(runs))
        }
        // Lists flattened to text by other writers (AppKit's DOCX): an indented "\t•\t" / "\t2\t" paragraph.
        if let style, style.headIndent > 0, let first = runs.first,
           let marker = first.text.range(of: #"^\t?([•◦▪‣⁃∙·–\-*]|\d{1,3}[.)]?|[a-zA-Z][.)])\t"#, options: .regularExpression) {
            let ordered = first.text[marker].contains { $0.isLetter || $0.isNumber }
            runs[0].text.removeSubrange(marker)
            let depth = max(1, Int((style.headIndent / 36).rounded()))
            return DocumentBlock(kind: .listItem(ordered: ordered, depth: depth), runs: trimmed(runs))
        }
        let textRuns = runs.filter { !$0.text.trimmingCharacters(in: .whitespaces).isEmpty }
        if !textRuns.isEmpty && textRuns.allSatisfy(\.code) && runs.allSatisfy({ $0.image == nil }) {
            return DocumentBlock(kind: .code, runs: [Run(text: runs.map(\.text).joined())])
        }
        if let level = headingLevel(text, range: range, style: style, bodySize: bodySize) {
            return DocumentBlock(kind: .heading(level), runs: trimmed(runs).map { var run = $0; run.bold = false; return run })
        }
        if let style, style.headIndent > 0, style.firstLineHeadIndent > 0, style.firstLineHeadIndent == style.headIndent {
            return DocumentBlock(kind: .quote, runs: trimmed(runs))
        }
        return DocumentBlock(kind: .paragraph, runs: trimmed(runs))
    }

    private static func runs(in text: NSAttributedString, range: NSRange) -> [Run] {
        var runs: [Run] = []
        text.enumerateAttributes(in: range) { attributes, subrange, _ in
            let piece = (text.string as NSString).substring(with: subrange)
            if let attachment = attributes[.attachment] as? NSTextAttachment {
                if let image = imageData(attachment) { runs.append(Run(text: "", image: image)) }
                return
            }
            let font = attributes[.font] as? NSFont
            let traits = font?.fontDescriptor.symbolicTraits ?? []
            var run = Run(text: piece.replacingOccurrences(of: "\u{FFFC}", with: ""))
            run.bold = traits.contains(.bold)
            run.italic = traits.contains(.italic)
            run.code = traits.contains(.monoSpace)
            run.strike = (attributes[.strikethroughStyle] as? Int ?? 0) != 0
            run.link = attributes[.link] as? URL ?? (attributes[.link] as? String).flatMap(URL.init(string:))
            if let last = runs.last, last.image == nil, last.sameStyle(as: run) {
                runs[runs.count - 1].text += run.text
            } else {
                runs.append(run)
            }
        }
        return runs
    }

    private static func trimmed(_ runs: [Run]) -> [Run] {
        var runs = runs
        if let first = runs.firstIndex(where: { $0.image == nil }) {
            runs[first].text = String(runs[first].text.drop { $0 == " " || $0 == "\t" })
        }
        if let last = runs.lastIndex(where: { $0.image == nil }) {
            while runs[last].text.last == " " || runs[last].text.last == "\t" { runs[last].text.removeLast() }
        }
        return runs.filter { $0.image != nil || !$0.text.isEmpty }
    }

    private static func isOrdered(_ list: NSTextList) -> Bool {
        let format = list.markerFormat.rawValue
        return ["decimal", "alpha", "roman", "octal", "hex"].contains { format.contains($0) }
    }

    /// `headerLevel` when an importer set it, else short, entirely bold lines set ≥ 15% above the body size.
    private static func headingLevel(_ text: NSAttributedString, range: NSRange, style: NSParagraphStyle?, bodySize: CGFloat) -> Int? {
        if let level = style?.headerLevel, level > 0 { return min(level, 6) }
        guard range.length <= 200 else { return nil }
        var size: CGFloat = 0
        var allBold = true
        text.enumerateAttribute(.font, in: range) { value, subrange, _ in
            guard let font = value as? NSFont else { return }
            let piece = (text.string as NSString).substring(with: subrange)
            guard !piece.trimmingCharacters(in: .whitespaces).isEmpty else { return }
            size = max(size, font.pointSize)
            if !font.fontDescriptor.symbolicTraits.contains(.bold) { allBold = false }
        }
        let ratio = size / max(bodySize, 1)
        switch ratio {
        case 1.75...: return 1
        case 1.4...: return 2
        case 1.15...: return allBold ? 3 : nil
        default: return nil
        }
    }

    /// The font size covering most characters (the body text).
    private static func dominantFontSize(of text: NSAttributedString) -> CGFloat {
        var counts: [CGFloat: Int] = [:]
        text.enumerateAttribute(.font, in: NSRange(location: 0, length: text.length)) { value, range, _ in
            guard let font = value as? NSFont else { return }
            counts[font.pointSize.rounded(), default: 0] += range.length
        }
        return counts.max { $0.value < $1.value }?.key ?? 12
    }

    /// Image attachments as PNG/JPEG/GIF data (other formats are re-encoded as PNG).
    private static func imageData(_ attachment: NSTextAttachment) -> (data: Data, ext: String)? {
        if let wrapper = attachment.fileWrapper, wrapper.isRegularFile, let data = wrapper.regularFileContents {
            let ext = ((wrapper.preferredFilename ?? wrapper.filename ?? "") as NSString).pathExtension.lowercased()
            switch ext {
            case "png", "gif": return (data, ext)
            case "jpg", "jpeg": return (data, "jpg")
            default:
                if let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) { return (png, "png") }
            }
        }
        if let contents = attachment.contents, let png = NSBitmapImageRep(data: contents)?.representation(using: .png, properties: [:]) {
            return (png, "png")
        }
        guard let image = attachment.image, let tiff = image.tiffRepresentation,
              let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:])
        else { return nil }
        return (png, "png")
    }
}
